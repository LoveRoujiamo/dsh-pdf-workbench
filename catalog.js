/** Navigation groups with the operations each one owns, in catalog order. */
export function catalogView() {
  return {
    limits: LIMITS,
    groups: GROUP_DEFS.map((group) => ({
      ...group,
      operations: OPERATIONS.filter((operation) => operation.group === group.id).map((operation) => operation.id),
    })),
    operations: OPERATIONS,
  }
}

const BY_ID = new Map(OPERATIONS.map((operation) => [operation.id, operation]))

export function findOperation(id) {
  return BY_ID.get(id)
}
